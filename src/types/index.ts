export type ConversationStatus = 'open' | 'pending' | 'closed';

export interface Conversation {
  id: string;
  user_id: string;
  contact_id: string;
  status: ConversationStatus;
  /**
   * `| null` and not just optional: the column is nullable, PostgREST
   * returns an explicit `null` for an unowned thread, and "give this back
   * to the pool" is a write of `null` rather than an omission. Typed as
   * `?: string` alone, that write did not compile.
   */
  assigned_agent_id?: string | null;
  last_message_text?: string;
  /**
   * `content_type` of the newest message (migration 047). Lets a row show
   * that a photo arrived even when it carried a caption — the case parsing
   * `last_message_text` cannot see.
   */
  last_message_kind?: string | null;
  /** `media_url` of the newest message, for the row's thumbnail (047). */
  last_message_media_url?: string | null;
  last_message_at?: string;
  /**
   * Who wrote the last message, and whether it arrived — migration 056.
   *
   * The WhatsApp model for a list row: what went OUT carries ticks and a
   * name, what came IN carries neither. `sender_type` is the direction
   * (`customer` = inbound) and still separates a colleague from the
   * assistant; `sender_id` is null for a customer, for the bot, and for
   * everything written before 056.
   *
   * All three are `undefined` on a database without the migration, which
   * is why the row degrades to plain text rather than to an error.
   */
  last_message_sender_type?: 'customer' | 'agent' | 'bot' | null;
  last_message_sender_id?: string | null;
  last_message_status?: Message['status'] | null;
  unread_count: number;
  /** When it entered `pending`. Null in every other status (migration 045). */
  waiting_since?: string | null;
  /**
   * Hidden from the inbox lists — not deleted (migration 045). Cleared
   * automatically when the customer writes again, which is what makes
   * hiding the safe answer to "get this out of my way".
   */
  hidden_at?: string | null;
  hidden_by?: string | null;
  created_at: string;
  updated_at: string;
  contact?: Contact;
  /**
   * The open deal on this thread, if there is one.
   *
   * Populated by CONVERSATION_SELECT's embed of `deals` (FK
   * `deals.conversation_id`) and flattened by `normalizeConversation`. It is
   * what lets a conversation row show which stage the negotiation is in —
   * the single most useful thing to know while scanning a shared inbox,
   * because it tells you what the last message is probably about.
   *
   * One conversation can carry several deals over time; the flattening keeps
   * the most recent OPEN one, since a won or lost deal says nothing about
   * what the customer is writing about today.
   */
  deal?: ConversationDeal | null;
  /**
   * AI auto-reply state for this thread (migration 029 + 033):
   *  - `ai_autoreply_disabled` — the bot is paused here (a human took
   *    over, or the model handed off). Sticky until re-enabled.
   *  - `ai_reply_count` — how many times the bot has auto-replied,
   *    checked against the account's per-conversation cap.
   *  - `ai_handoff_summary` — short internal note the bot wrote when it
   *    handed off, shown to whoever takes the thread over.
   */
  ai_autoreply_disabled?: boolean;
  ai_reply_count?: number;
  ai_handoff_summary?: string | null;
}

