/** `media` arrived with migration 044 — a file with an optional caption. */
export type QuickReplyKind = 'text' | 'interactive' | 'media';

export interface QuickReply {
  id: string;
  /** Account tenancy key — shared across all members of the account. */
  account_id: string;
  /** Author / audit only. */
  user_id: string;
  title: string;
  kind: QuickReplyKind;
  /**
   * What you type after the slash, WITHOUT it: `orcamento`, not
   * `/orcamento`. Lower-case and unique per account (migration 044).
   *
   * Distinct from the title on purpose. The `/` panel can already find
   * "Prazo de entrega" from `/pra` by word prefix, and that is not the same
   * thing: a shortcut is a short name somebody decides once and then types
   * without reading, and it survives the title being reworded.
   */
  shortcut?: string | null;
  /** Set when `kind === 'text'` or `'media'` (the caption). */
  content_text?: string | null;
  /** Set when `kind === 'interactive'`. */
  interactive_payload?: InteractiveMessagePayload | null;
  /** Public chat-media URL. Set when `kind === 'media'` (migration 044). */
  media_url?: string | null;
  media_type?: string | null;
  created_at: string;
  updated_at: string;
}
